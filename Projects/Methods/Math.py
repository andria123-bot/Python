import math

a = (1, 2, 3, 4, 5)

print(abs(-13)) #გარდაქმნის დადებითად

print(round(5.5)) #ამრგვალებს უდიდეს რიცხვთან

print(pow(2, 4)) #აკვადრატებს

print(max(a)) #გამოაქვს უდიდესი რიცხვი

print(min(a)) #გამოაქვს უმცირესი რიცხვი

print(sum(a)) #გამოიტანს ჯამს

print(math.sqrt(9)) #აბრუნებს აკვადრატებულ ფესვს